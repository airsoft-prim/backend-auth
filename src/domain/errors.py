class ApplicationError(Exception):
    """Ошибка работы Auth Backend'a портала Airsoft Prim.

    Общий предок ошибок приложения; HTTP-слой выбирает обработчик по конкретному подклассу.
    """


class DomainError(ApplicationError):
    """Ошибка выполнения бизнес-логики.

    Объединяет ошибки прикладных сценариев и безопасности, отделяя их от отказов внешних ресурсов.
    """


class ServiceError(DomainError):
    """Ошибка в работе служб.

    Обозначает ошибки выполнения прикладных сценариев; специализированные подклассы уточняют
    нарушенное условие.
    """


class SecurityError(DomainError):
    """Ошибка безопасности.

    Объединяет ошибки идентификации, аутентификации, авторизации и работы с JWT для HTTP-
    обработчиков.
    """


class ProviderError(ApplicationError):
    """Ошибка выполнения инфраструктурной логики.

    Обозначает отказ внешнего ресурса. HTTP-обработчик возвращает ответ `500` без раскрытия
    подробностей инфраструктуры.
    """


class RepositoryError(ProviderError):
    """Ошибка в работе репозиториев.

    Оборачивает исключения операций с БД, `Redis` и файлами. Исходная ошибка сохраняется как
    причина исключения.
    """


class UserAlreadyExistsError(ServiceError):
    """Ошибка регистрации: учётная запись с таким `username` или `email` уже есть.

    Сигнализирует конфликт уникальности логина или адреса почты при регистрации; HTTP-слой
    возвращает ответ `409`.
    """


class UserIdentificationError(SecurityError):
    """Ошибка идентификации пользователя.

    Сигнализирует, что учётную запись нельзя определить: она отсутствует, заблокирована при входе
    или не имеет идентификатора.
    """


class UserAuthenticationError(SecurityError):
    """Ошибка аутентификации пользователя.

    Сигнализирует несовпадение пароля при входе. HTTP-слой использует тот же ответ `401`, что и для
    ошибки идентификации.
    """


class UserAuthorizationError(SecurityError):
    """Ошибка отсутствия обязательного токена.

    Сигнализирует отсутствие токена в заголовке или cookie. HTTP-слой возвращает ответ `401`.
    """


class JWTEncryptionError(SecurityError):
    """Ошибка выпуска JWT-токена.

    Сигнализирует отсутствие или неподходящий формат приватного ключа подписи. HTTP-слой возвращает
    ответ `500`.
    """


class JWTDecryptionError(SecurityError):
    """Ошибка проверки и чтения JWT-токена.

    Объединяет ошибки заголовка, подписи и `claims` JWT. HTTP-слой возвращает ответ `403` без
    раскрытия причины проверки.
    """


class TokenRevokedError(JWTDecryptionError):
    """Ошибка проверки отозванного токена.

    Специализирует `JWTDecryptionError` для токена или сессии, помеченных отозванными.
    """


class SessionNotFoundError(ServiceError):
    """Ошибка доступа к сессии: сессии нет или она не принадлежит пользователю.

    Не различает отсутствие сессии и несовпадение её владельца. HTTP-слой возвращает ответ `404`.
    """
